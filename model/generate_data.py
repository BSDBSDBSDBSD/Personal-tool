def generate(per_intent=600):
    data = []
    for name, fn in INTENTS.items():
        seen = set()
        tries = 0
        while len(seen) < per_intent and tries < per_intent * 20:
            tries += 1
            seen.add(fn())
        data.extend((s, name) for s in seen)
    R.shuffle(data)
    return data


